"""PR の題名と本文の検査。過去に実際に通ってしまった題名で落ちることを確かめる。"""
import unittest

from scripts.check_pr_text import headings, problems

# main に入った・出された英語の題名（#117・#24・#186）
PAST_TITLES = [
    "Stop install_hooks from writing into a shared core.hooksPath directory",
    "Fix vote comparison eligibility and clarify proposal boundaries",
    "Bump @vitejs/plugin-react from 6.1.2 to 6.2.1 in /app",
]


class CheckPrTextTest(unittest.TestCase):
    def test_past_english_titles_fail(self):
        for t in PAST_TITLES:
            self.assertTrue(problems(t, ""), t)

    def test_japanese_title_passes(self):
        self.assertEqual(problems("parse_cabinet.py で --help を解釈する", "## 原因\n\n本文"), [])
        self.assertEqual(problems("依存の更新 Bump vite from 8.3.3 to 8.3.6 in /app", ""), [])

    def test_english_heading_fails_but_code_fence_is_ignored(self):
        self.assertTrue(problems("題名", "## Summary\n本文"))
        body = "## 検査\n```\n# Tests  7 passed (7)\n```\n"
        self.assertEqual(headings(body), ["## 検査"])
        self.assertEqual(problems("題名", body), [])


    def test_past_footers_fail(self):
        # #254 と #248 の本文の末尾に残ったフッター
        for footer in ["_Generated by [Claude Code](https://claude.ai/code)_", "🤖 Generated with [Claude Code](https://claude.com/claude-code)"]:
            self.assertTrue(problems("題名", "## 原因\n本文\n\n---\n" + footer), footer)


if __name__ == "__main__":
    unittest.main()
