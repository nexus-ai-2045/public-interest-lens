"""PR の題名と本文を検査する（CI の pr-text と、手元で PR を作る前に同じものを回す）。

落とすもの：
- 題名に日本語（かな・漢字）が無い（AGENTS.md「PR の題名と見出しは日本語」）。
- 本文の見出し（# で始まる行。コードの囲みの中は見ない）に日本語が無い。
- 本文に道具の自動フッター（Generated by/with Claude Code）が残っている（進め方 3章10）。
  フッターは PR の作成のときにサーバーが付ける（2026-11-20 に #278 で確認。本文の更新では付け直されない）。
  CI は --fix で、検査の前にフッターを本文から外して PR を更新する（人も AI も外す手順を覚えなくてよい）。

使い方：
  python3 scripts/check_pr_text.py --title "題名" [--body-file 本文.md]
  python3 scripts/check_pr_text.py --from-event "$GITHUB_EVENT_PATH" [--fix]   # CI（pull_request のイベント JSON）
  --fix：フッターを外した本文で PR を更新してから検査する（環境変数 GITHUB_TOKEN と GITHUB_REPOSITORY を使う）。
終了コード：合格 0、不合格 1。
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import urllib.request
from pathlib import Path

JAPANESE = re.compile(r"[぀-ヿ㐀-鿿ｦ-ﾟ]")
FENCE = re.compile(r"^\s*(`{3,}|~{3,})")
HEADING = re.compile(r"^\s{0,3}#{1,6}\s+\S")
FOOTER = re.compile(r"Generated (by|with) \[?Claude Code\]?")


def headings(body: str) -> list[str]:
    out, fence = [], ""
    for line in body.splitlines():
        m = FENCE.match(line)
        if m:
            mark = m.group(1)
            if not fence:
                fence = mark
            elif mark[0] == fence[0] and len(mark) >= len(fence):
                fence = ""
            continue
        if not fence and HEADING.match(line):
            out.append(line.strip())
    return out


def strip_footer(body: str) -> str:
    """フッターの行と、その直前の区切り線（---）と空行を外す。ほかの行は変えない。"""
    lines = body.splitlines()
    if not any(FOOTER.search(line) for line in lines):
        return body
    kept = [line for line in lines if not FOOTER.search(line)]
    while kept and kept[-1].strip() in ("", "---"):
        kept.pop()
    return "\n".join(kept)


def update_body(repo: str, number: int, body: str, token: str) -> None:
    req = urllib.request.Request(
        f"https://api.github.com/repos/{repo}/pulls/{number}",
        data=json.dumps({"body": body}).encode("utf-8"),
        method="PATCH",
        headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json"},
    )
    with urllib.request.urlopen(req, timeout=30) as res:
        res.read()


def problems(title: str, body: str) -> list[str]:
    found = []
    if not JAPANESE.search(title):
        found.append(f"題名が日本語でない：{title!r}（題名は日本語で書く。dependabot の PR も題名を直してから通す）")
    for h in headings(body):
        if not JAPANESE.search(h):
            found.append(f"見出しが日本語でない：{h!r}")
    if FOOTER.search(body):
        found.append("本文に道具の自動フッターが残っている（作成後に本文を更新して外す）")
    return found


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--title")
    ap.add_argument("--body-file", type=Path)
    ap.add_argument("--from-event", type=Path, help="GitHub の pull_request イベントの JSON")
    ap.add_argument("--fix", action="store_true", help="フッターを外した本文で PR を更新してから検査する（--from-event と使う）")
    a = ap.parse_args(argv)
    if a.fix and not a.from_event:
        ap.error("--fix は --from-event と使う")
    if a.from_event:
        pr = json.loads(a.from_event.read_text(encoding="utf-8"))["pull_request"]
        title, body = pr.get("title") or "", pr.get("body") or ""
        if a.fix and strip_footer(body) != body:
            body = strip_footer(body)
            update_body(os.environ["GITHUB_REPOSITORY"], int(pr["number"]), body, os.environ["GITHUB_TOKEN"])
            print("直した：本文から自動フッターを外して PR を更新した")
    elif a.title is not None:
        title = a.title
        body = a.body_file.read_text(encoding="utf-8") if a.body_file else ""
    else:
        ap.error("--title か --from-event を渡す")
    found = problems(title, body)
    for p in found:
        print(f"不合格：{p}")
    if not found:
        print("合格：PR の題名と本文")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
