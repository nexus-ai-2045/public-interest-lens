"""団体名の表記をそろえるキー（政治資金の寄附者と審議会の団体の帳簿を結ぶため）。

org_key() は名前の比較用で、表示には元の名前を使う。そろえるのは表記の揺れだけで、
別の団体を1つにまとめる推測（略称の展開・支部の統合など）はしない。
"""
from __future__ import annotations

import re
import unicodedata

# 法人格（前株・後株とも）。長いものから外す。
LEGAL_FORMS = (
    "公益社団法人", "公益財団法人", "一般社団法人", "一般財団法人", "特定非営利活動法人", "社会福祉法人",
    "医療法人社団", "医療法人財団", "医療法人", "学校法人", "宗教法人", "独立行政法人", "国立大学法人",
    "株式会社", "有限会社", "合同会社", "合資会社", "合名会社", "協同組合連合会",
    "NPO法人", "(株)", "(有)", "(社)", "(財)", "(一社)", "(一財)", "(公社)", "(公財)", "(医)", "(学)", "(福)", "(宗)", "(特非)",
)
# 囲み文字（㈱ など）は NFKC で (株) になる。
SPACES = re.compile(r"\s+")


def org_key(name: str) -> str:
    """NFKC にし、空白を消し、法人格を外した名前。空や法人格だけなら空文字。"""
    text = SPACES.sub("", unicodedata.normalize("NFKC", name or ""))
    for form in LEGAL_FORMS:
        text = text.replace(form, "")
    return text.strip("・ ")
