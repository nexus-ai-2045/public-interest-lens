def norm(text: str) -> str:
    return unicodedata.normalize("NFKC", text or "")


def classify(title: str) -> tuple[str, str, str, str]:
    """(経路の符号, 類型, 結果, 理由)。"""
    t = norm(title)
    for code, kind, result, reason, words in RULES:
        if any(norm(w) in t for w in words):
            return code, kind, result, reason
    return FALLBACK


def approved(row: dict) -> bool:
    return row["審議状況"] in ("両院承認", "承認")


def build() -> list[dict]:
    with SRC.open(encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    out = []
    for r in rows:
        code, kind, result, reason = classify(r["題名"])
        out.append({
            "id": f"{r['種別']}-{r['提出回次']}-{r['番号']}", "種別": r["種別"], "題名": r["題名"], "類型": kind, "結果": result,
            "理由": reason, "経路": code, "審議状況": r["審議状況"], "議決日_衆": r["議決日_衆"], "議決日_参": r["議決日_参"],
            "賛成会派_衆": r["賛成会派_衆"], "反対会派_衆": r["反対会派_衆"],
        })
    return out


def main() -> int:
    rows = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=HEADER)
        w.writeheader()
        w.writerows(rows)
    print(f"{len(rows)}件", dict(Counter(r["結果"] for r in rows)))
    print(dict(Counter(r["類型"] for r in rows)))
    return 0


