// 名簿の「会派」の略称を、画面に出す党名に直す。
// 国会の名簿（衆議院の議員一覧・参議院の議員一覧）に載るのは院内の会派だけで、党籍は載らない。
// 略称のまま「所属政党」として出すと、参議院の「民主」（国民民主党・新緑風会）が民主党に見えるなど、読み違えを生む。
// 対応は公式の表記だけで決める：参議院は第221回国会の投票名簿（data/acquired/sangiin-votes/members.csv）の会派名、
// 衆議院は議員一覧の会派欄と議案の経過の会派名。公式の表記から党名が決まらない略称は、そのまま「（会派）」を付けて出す。
// 会派の中に無所属の議員がいても名簿からは区別できない（立憲民主・無所属、自由民主党・無所属の会など）ので、会派の党名で出す。

const TABLE: Record<string, Record<string, string>> = {
  衆議院: { 自民: '自由民主党', 中道: '中道改革連合', 維新: '日本維新の会', 国民: '国民民主党', 参政: '参政党', みらい: 'チームみらい', 共産: '日本共産党', 無: '無所属' },
  参議院: {
    自民: '自由民主党', 立憲: '立憲民主党', 民主: '国民民主党', 公明: '公明党', 維新: '日本維新の会', 参政: '参政党', 共産: '日本共産党',
    い党: 'れいわ新選組', みら: 'チームみらい', 保守: '日本保守党', 沖縄: '沖縄の風（会派）', 社民: '社会民主党', 無所属: '無所属',
  },
};

/** 名簿の会派の略称 → 画面に出す所属。決められない略称は「略称（会派）」にして、党名だと読めないようにする。 */
export function affiliationOf(house: string, abbreviation: string): string {
  return TABLE[house]?.[abbreviation] ?? `${abbreviation}（会派）`;
}
