import { describe, expect, it } from 'vitest';
import { cabinetForBill } from './cabinet-members';
import { parseCsv } from './impact-batch';

const HEAD = '回次,種別,提出回次,番号,題名,提出者,提出者一覧,付託日_衆,議決日_衆,議決日_参\n';
const CAB = '区分,役職,氏名,就任日_西暦,退任日_西暦\n';
const namesOf = (enacted: string, cabinet: string) => {
  const rows = parseCsv(HEAD + enacted);
  const of = cabinetForBill(rows, parseCsv(CAB + cabinet));
  return (session: string, no: string) => of(rows.find(r => r['提出回次'] === session && r['番号'] === no)!).names.slice().sort();
};

describe('閣法の提出者＝閣僚の割り出し', () => {
  it('首相1人に付けず、会期の最初から最後まで在任した閣僚の全員。途中で替わった閣僚・副大臣・副長官・法制局長官は入れない', () => {
    const of = namesOf('171,閣法,171,1,甲法案,,,平成21年 1月 5日,,\n171,閣法,171,2,乙法案,,,平成21年 6月 5日,,\n',
      '閣僚,内閣総理大臣,首相 一,2008-09-24,\n閣僚,財務大臣,財務 二,2008-09-24,\n閣僚,法務大臣,法務 三,2008-09-24,2009-03-01\n閣僚,法務大臣,法務 四,2009-03-01,\n'
      + '副大臣,財務副大臣,副 五,2008-09-24,\n閣僚,内閣官房副長官,官房 六,2008-09-24,\n閣僚,内閣法制局長官,法制 七,2008-09-24,\n');
    expect(of('171', '1')).toEqual(['財務二', '首相一']);
  });

  it('総理大臣が会期中に替わる回次は、交代より前に付託された閣法だけ付託日の閣僚。交代より後の付託は決められないので空', () => {
    const of = namesOf('171,閣法,171,1,甲法案,,,平成21年 1月 5日,,\n171,閣法,171,2,乙法案,,,平成21年 6月 5日,,\n',
      '閣僚,内閣総理大臣,首相 一,2008-09-24,2009-03-01\n閣僚,内閣総理大臣,首相 二,2009-03-01,\n閣僚,財務大臣,財務 三,2008-09-24,\n'
      + '閣僚,法務大臣,法務 四,2008-09-24,2009-03-01\n閣僚,法務大臣,法務 五,2009-03-01,\n');
    expect(of('171', '1')).toEqual(['法務四', '財務三', '首相一']);
    expect(of('171', '2')).toEqual([]);
  });

  it('名簿が会期の途中から脚注の印（*）つきで書く閣僚も、同じ人として通して在任に数える', () => {
    const of = namesOf('180,閣法,180,1,甲法案,,,平成24年 2月 1日,,\n180,閣法,180,2,乙法案,,,平成24年 8月 1日,,\n',
      '閣僚,内閣総理大臣,首相 一,2011-09-02,\n閣僚,財務大臣,財務 二,2011-09-02,2012-06-04\n閣僚,財務大臣,財務 二*,2012-06-04,\n');
    expect(of('180', '1')).toEqual(['財務二', '首相一']);
  });

  it('提出した回次の内閣に付け、継続審査で後の回次に付託された閣法は決められないので空', () => {
    const of = namesOf('169,閣法,169,1,甲法案,,,平成20年 2月 1日,,\n169,閣法,169,2,乙法案,,,平成20年 5月 1日,,\n170,閣法,169,3,丙法案,,,平成20年 9月24日,,\n'
      + '171,閣法,171,1,丁法案,,,平成21年 1月 5日,,\n171,閣法,171,2,戊法案,,,平成21年 9月20日,,\n172,閣法,171,3,己法案,,,平成21年10月 1日,,\n',
      '閣僚,内閣総理大臣,前 首相,2007-09-26,2008-09-24\n閣僚,内閣総理大臣,後 首相,2008-09-24,2009-09-16\n閣僚,内閣総理大臣,次 首相,2009-09-16,\n');
    expect(of('169', '3')).toEqual(['前首相']);
    expect(of('171', '1')).toEqual(['後首相']);
    expect(of('171', '3')).toEqual([]);
  });
});
